<?php

namespace App\Services\CallPro;

/**
 * Утасны дугаарыг өвчтөнтэй тааруулахад тохиромжтой хэлбэрт шилжүүлнэ.
 *
 * CallPro дугаарыг integer-ээр илгээдэг тул урд талын 0 эсвэл +976 алдагдаж
 * болзошгүй. Нэг дугаарыг өөр өөр хэлбэрээр («+976 9911-2233», «99112233»)
 * хүлээж авсан ч нэг л дугаар гэж таних шаардлагатай — давтан залгасныг
 * тоолох, спам жагсаалттай жиших хоёулаа үүн дээр тулгуурладаг.
 */
class PhoneNormalizer
{
    /** Жишиход бэлэн хэлбэр (8 орон). Дотуур дугаар мэт богино бол null. */
    public static function normalize(string|int|null $raw): ?string
    {
        $digits = preg_replace('/\D+/', '', (string) $raw) ?? '';

        if ($digits === '') {
            return null;
        }

        // Улсын код (976) залгасан бол хасна.
        if (strlen($digits) > 8 && str_starts_with($digits, '976')) {
            $digits = substr($digits, 3);
        }

        // Олон улсын урт дугаарын сүүлийн 8 орноор жишихэд алдаа гарах тул
        // 8-аас урт хэвээр байвал сүүлийн 8-ыг авна (дотоодын дугаар гэж үзнэ).
        if (strlen($digits) > 8) {
            $digits = substr($digits, -8);
        }

        // 8-аас богино бол дотуур дугаар / үйлчилгээний дугаар — өвчтөнтэй
        // тааруулах утгагүй.
        return strlen($digits) === 8 ? $digits : null;
    }
}
