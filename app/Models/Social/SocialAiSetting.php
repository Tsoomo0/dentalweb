<?php

namespace App\Models\Social;

use Illuminate\Database\Eloquent\Model;

class SocialAiSetting extends Model
{
    protected $table = 'social_ai_settings';

    protected $fillable = [
        'enabled',
        'provider',
        'mode',
        'system_rules',
        'extra_knowledge',
        'model',
    ];

    protected $casts = [
        'enabled' => 'boolean',
    ];

    /** Singleton — үргэлж ганц мөр (id=1) ашиглана. */
    public static function current(): self
    {
        return static::firstOrCreate(['id' => 1]);
    }

    /** AI-гийн үндсэн дүрэм (админ засаагүй үед). */
    public static function defaultRules(): string
    {
        return <<<'RULES'
        1. Мэндчилгээ: ярианы ХАМГИЙН ЭХЭНД л нэг удаа богино мэндэл. Өмнө нь ярьж/мэндэлсэн бол дахин БҮҮ мэндэл — шууд асуултад нь хариул.
        2. БЭЛЭН ХАРИУЛТ: доорх мэдээлэлд (ялангуяа оруулсан FAQ-д) асуултад тохирох бэлэн бичсэн хариулт байвал түүнийг АЛЬ БОЛОХ ЯГ ТЭР ҮГЭЭР нь ашигла — өөрөө шинээр бүү найруул. Ингэснээр монгол найруулга төгс, жигд байна.
        3. Тодруулах: ерөнхий буюу тодорхойгүй асуулт ирвэл (жишээ нь зүгээр «үнэ») бүх жагсаалтыг бүү асга. Эхлээд «Та яг ямар эмчилгээ/үйлчилгээний талаар мэдэхийг хүсэж байна вэ?» гэж товч тодруул.
        4. Тохирсон хариу: асуултын сэдэвт л тохирсон мэдээллийг өг. Аппаратын талаар асуувал аппаратын ТӨРЛҮҮДИЙГ, эмчийн талаар асуувал эмчийг, үнийн талаар асуувал тухайн үнийг өг. Хамааралгүй мэдээллийг бүү холь.
        5. Товч, эелдэг, хүн шиг: 1-3 өгүүлбэр. Emoji-г хэмжээтэй ашигла.
        6. Онош тавихгүй, эмчилгээний нарийн зөвлөгөө өгөхгүй — «эмчид үзүүлэхийг» зөвлө.
        7. Мэдээлэлд байхгүй зүйлийг зохиохгүй, үнэ/баримтыг бүү таа. Мэдэхгүй зүйлийг дур мэдэн бүү хариул — ажилтанд холбо.
        RULES;
    }
}
